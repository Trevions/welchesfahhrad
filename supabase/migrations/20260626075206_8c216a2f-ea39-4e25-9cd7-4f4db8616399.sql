<h2>Welcher Federweg passt zu welchem Einsatz?</h2>
<ul>
<li><strong>20–25 mm:</strong> Gravel-Rennen, schnelle Endurance-Touren. Wenig Bewegung, kaum Effizienzverlust im Wiegetritt.</li>
<li><strong>30–40 mm:</strong> Trekking, Pendeln, Bikepacking. Der Sweetspot für Stadt + Land.</li>
<li><strong>50 mm und mehr:</strong> Forstwege, Kopfsteinpflaster, lange Tagestouren. Spürbar mehr Komfort, leichter Pumpeffekt bergauf.</li>
</ul>

